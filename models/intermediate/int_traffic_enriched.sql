SELECT
    EVENT_ID,
    EVENT_TIMESTAMP,
    ROAD_ID,
    ROAD_NAME,
    CITY,
    LATITUDE,
    LONGITUDE,
    VEHICLE_COUNT,
    AVERAGE_SPEED_KMH,
    OCCUPANCY_PERCENT,
    WEATHER_CONDITION,
    TEMPERATURE_C,
    RAINFALL_MM,
    INCIDENT_FLAG,

    EXTRACT(HOUR FROM EVENT_TIMESTAMP) AS HOUR_OF_DAY,

    DAYOFWEEK(EVENT_TIMESTAMP) AS DAY_OF_WEEK,

    CASE
        WHEN AVERAGE_SPEED_KMH < 20
             OR OCCUPANCY_PERCENT >= 85
            THEN 'HIGH'
        WHEN AVERAGE_SPEED_KMH < 35
             OR OCCUPANCY_PERCENT >= 65
            THEN 'MEDIUM'
        ELSE 'LOW'
    END AS CONGESTION_LEVEL,

    CASE
        WHEN AVERAGE_SPEED_KMH < 20 THEN 'VERY_SLOW'
        WHEN AVERAGE_SPEED_KMH < 35 THEN 'SLOW'
        WHEN AVERAGE_SPEED_KMH < 50 THEN 'NORMAL'
        ELSE 'FAST'
    END AS SPEED_CATEGORY,

    CASE
        WHEN EXTRACT(HOUR FROM EVENT_TIMESTAMP) BETWEEN 7 AND 10
          OR EXTRACT(HOUR FROM EVENT_TIMESTAMP) BETWEEN 17 AND 21
            THEN TRUE
        ELSE FALSE
    END AS IS_PEAK_HOUR

FROM {{ ref('stg_traffic_events') }}